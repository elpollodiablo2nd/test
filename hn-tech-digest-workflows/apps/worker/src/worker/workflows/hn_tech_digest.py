from datetime import timedelta
from html import escape
from urllib.parse import urlparse

import pydantic

import mistralai.workflows as workflows
from mistralai.workflows import Depends
from mistralai.workflows.plugins.mistralai import (
    ChatCompletionRequest,
    SystemMessage,
    UserMessage,
    chat_parse_to_model,
    get_mistral_client,
)
from mistralai.workflows.plugins.mistralai.connectors import (
    ToolCallClient,
    connector,
    uses_connectors,
)

gmail_connector = connector("gmail")
hacker_news_connector = connector("hacker-news-api")

HN_API_CONNECTOR = "hacker-news-api"
HN_SEARCH_TOOL = "search_stories"
HN_ITEM_BASE = "https://news.ycombinator.com/item?id="
CHAT_MODEL = "mistral-large-latest"
TTS_MODEL = "voxtral-mini-tts-3-0"
DEFAULT_VOICE_ID = "gb_jane_neutral"
DEFAULT_RECIPIENT = "fhaidt@gmail.com"
DEFAULT_FRONT_PAGE_LIMIT = 30
DEFAULT_MAX_STORIES = 8
MAX_PODCAST_WORDS = 320
MAX_ATTACHMENT_B64_CHARS = 4_128_768


class HnTechDigestInput(pydantic.BaseModel):
    recipient: str = DEFAULT_RECIPIENT
    voice_id: str = DEFAULT_VOICE_ID
    max_stories: int = DEFAULT_MAX_STORIES
    front_page_limit: int = DEFAULT_FRONT_PAGE_LIMIT
    dry_run: bool = False


class HnStory(pydantic.BaseModel):
    id: int
    title: str
    url: str | None = None
    score: int = 0
    by: str = ""
    descendants: int = 0
    hn_url: str


class DigestStory(pydantic.BaseModel):
    rank: int
    title: str
    url: str | None = None
    hn_url: str
    score: int
    comments: int
    summary: str


class Digest(pydantic.BaseModel):
    date: str
    stories: list[DigestStory]
    digest_markdown: str
    podcast_script: str


class HnTechDigestResult(pydantic.BaseModel):
    recipient: str
    subject: str
    story_count: int
    digest_markdown: str
    podcast_script_words: int
    audio_filename: str | None = None
    audio_bytes: int | None = None
    email_message_id: str | None = None
    email_thread_id: str | None = None
    dry_run: bool = False


def story_domain(url: str | None) -> str:
    if not url:
        return "news.ycombinator.com"
    host = urlparse(url).hostname or ""
    return host.removeprefix("www.")


def parse_algolia_hit(hit: object) -> HnStory | None:
    if not isinstance(hit, dict):
        return None
    title = hit.get("title")
    object_id = hit.get("objectID", hit.get("story_id"))
    if not title or object_id is None:
        return None
    try:
        story_id = int(object_id)
    except (ValueError, TypeError):
        return None
    return HnStory(
        id=story_id,
        title=str(title),
        url=hit.get("url"),
        score=int(hit.get("points") or 0),
        by=str(hit.get("author") or ""),
        descendants=int(hit.get("num_comments") or 0),
        hn_url=f"{HN_ITEM_BASE}{story_id}",
    )


def unwrap_tool_result(result: object) -> object:
    if not isinstance(result, dict):
        return result
    structured = result.get("structuredContent")
    if structured is not None:
        return structured
    content = result.get("content")
    if isinstance(content, list):
        import json

        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                try:
                    return json.loads(block.get("text", ""))
                except (ValueError, TypeError):
                    continue
        return None
    return result


def render_digest_html(digest: Digest) -> str:
    rows = []
    for story in digest.stories:
        link = escape(story.url or story.hn_url, quote=True)
        title = escape(story.title)
        summary = escape(story.summary)
        domain = escape(story_domain(story.url))
        discussion = escape(story.hn_url, quote=True)
        rows.append(
            "<li>"
            f'<a href="{link}"><strong>{title}</strong></a>'
            f" &mdash; {summary}"
            f" <small>({story.score} points, {story.comments} comments, {domain},"
            f' <a href="{discussion}">HN discussion</a>)</small>'
            "</li>"
        )
    heading = escape(digest.date)
    return (
        f"<h2>HN Tech Digest &mdash; {heading}</h2>"
        "<ol>" + "".join(rows) + "</ol>"
        "<p><small>Podcast-style audio digest (MP3, 1&ndash;2 minutes) is attached to this email."
        " Generated by the hn-tech-digest Mistral workflow from the Hacker News front page.</small></p>"
    )


SYSTEM_PROMPT = """You are the editor of a daily tech-industry news digest built from the Hacker News front page.

Your job:
1. Select up to the requested number of stories that are TECH INDUSTRY news. Include: product and platform launches by tech companies, AI models and AI companies, semiconductors and hardware, big-tech business news (earnings, layoffs, M&A, antitrust), tech policy and regulation with industry impact, developer tools and infrastructure, cybersecurity industry news, and open-source projects with real industry impact. Exclude: personal blogs, essays and opinion pieces, non-tech news (politics, sports, general science with no industry angle), Ask HN / Show HN posts unless they carry substantive industry signal, and anything off-topic for a tech professional.
2. Rank the selected stories by a mix of score and industry importance.
3. Write a 1-2 sentence factual summary per story, naming the company, product, or technology involved.
4. Produce digest_markdown: a Markdown digest titled with the date, with a numbered list. Each entry: the linked headline (use the story URL, or the HN discussion URL when there is no external URL), the summary, and a meta line with score, comment count, source domain, and a link to the HN discussion.
5. Produce podcast_script: a spoken-word script of 180-260 words (about 1-2 minutes at a normal speaking pace). It must start with a short intro naming the date, then cover each selected story as a headline plus a one-or-two-sentence takeaway, and end with a one-line sign-off. Write for the ear: no Markdown, no URLs, no bullet symbols; spell out or phrase names so they are pronounced sensibly (for example write "A.I." for AI). Do not invent facts beyond the story titles and your knowledge cutoff.

Return the Digest JSON exactly as structured; do not wrap it in prose."""


def build_story_listing(stories: list[HnStory]) -> str:
    return "\n".join(
        f"- id={s.id} | score={s.score} | comments={s.descendants} | by={s.by}"
        f" | domain={story_domain(s.url)} | url={s.url or s.hn_url} | title={s.title}"
        for s in stories
    )


@workflows.activity(
    name="fetch-front-page-stories",
    start_to_close_timeout=timedelta(seconds=90),
    retry_policy_max_attempts=3,
)
async def fetch_front_page_stories(
    limit: int, hn: ToolCallClient = Depends(hacker_news_connector)
) -> list[HnStory]:
    result = await hn.call_tool(
        tool_name=HN_SEARCH_TOOL,
        arguments={"tags": "front_page", "hitsPerPage": limit},
    )
    payload = unwrap_tool_result(result)
    hits = payload.get("hits") if isinstance(payload, dict) else None
    if not isinstance(hits, list):
        raise RuntimeError(
            f"connector '{HN_API_CONNECTOR}' tool '{HN_SEARCH_TOOL}' returned no hits: "
            f"{str(payload)[:300]}"
        )
    stories = [s for hit in hits if (s := parse_algolia_hit(hit)) is not None]
    if not stories:
        raise RuntimeError("Hacker News front page returned no usable stories")
    return stories


@workflows.activity(
    name="build-tech-digest",
    start_to_close_timeout=timedelta(seconds=240),
    retry_policy_max_attempts=3,
)
async def build_tech_digest(
    stories: list[HnStory], max_stories: int, today: str
) -> Digest:
    user_prompt = (
        f"Today is {today}. These are the current Hacker News front-page stories "
        f"(newest ranked first):\n\n{build_story_listing(stories)}\n\n"
        f"Select up to {max_stories} tech-industry stories and return the Digest."
    )
    request = ChatCompletionRequest(
        model=CHAT_MODEL,
        messages=[
            SystemMessage(content=SYSTEM_PROMPT),
            UserMessage(content=user_prompt),
        ],
        temperature=0.2,
    )
    digest = await chat_parse_to_model(Digest, request)
    digest.date = today
    digest.stories = digest.stories[:max_stories]
    for rank, story in enumerate(digest.stories, start=1):
        story.rank = rank
    return digest


@workflows.activity(
    name="generate-podcast-audio",
    start_to_close_timeout=timedelta(seconds=240),
    retry_policy_max_attempts=2,
)
async def generate_podcast_audio(script: str, voice_id: str) -> str:
    words = len(script.split())
    if words > MAX_PODCAST_WORDS:
        raise ValueError(
            f"podcast script is {words} words, above the {MAX_PODCAST_WORDS} limit"
        )
    client = get_mistral_client()
    response = await client.audio.speech.complete_async(
        model=TTS_MODEL,
        input=script,
        voice_id=voice_id,
        response_format="mp3",
    )
    audio_b64 = response.audio_data
    if len(audio_b64) > MAX_ATTACHMENT_B64_CHARS:
        raise ValueError(
            f"generated audio is {len(audio_b64)} base64 chars, above the "
            f"{MAX_ATTACHMENT_B64_CHARS} Gmail attachment limit"
        )
    return audio_b64


def extract_sent_message(result: object) -> dict:
    payload = unwrap_tool_result(result)
    return payload if isinstance(payload, dict) else {}


@workflows.activity(
    name="send-digest-email",
    start_to_close_timeout=timedelta(seconds=120),
    retry_policy_max_attempts=2,
)
async def send_digest_email(
    recipient: str,
    subject: str,
    body_markdown: str,
    html_body: str,
    audio_b64: str,
    audio_filename: str,
    gmail: ToolCallClient = Depends(gmail_connector),
) -> dict:
    result = await gmail.call_tool(
        tool_name="send_email",
        arguments={
            "to": [recipient],
            "subject": subject,
            "body": body_markdown,
            "htmlBody": html_body,
            "attachments": [
                {
                    "filename": audio_filename,
                    "mimeType": "audio/mpeg",
                    "content": audio_b64,
                }
            ],
        },
    )
    return extract_sent_message(result)


@workflows.workflow.define(
    name="hn-tech-digest",
    workflow_display_name="HN Tech Digest",
    workflow_description=(
        "One-shot, user-triggered digest: fetches the Hacker News front page via the "
        "'hacker-news-api' connector, selects the top tech-industry stories, summarizes "
        "them, renders a 1-2 minute podcast-style MP3, and emails both to your own Gmail "
        "inbox. No schedule; start it manually."
    ),
    on_behalf_of=True,
)
@uses_connectors(gmail_connector, hacker_news_connector)
class HnTechDigestWorkflow:
    @workflows.workflow.entrypoint
    async def run(self, input: HnTechDigestInput) -> HnTechDigestResult:
        today = workflows.workflow.now().strftime("%Y-%m-%d")
        stories = await fetch_front_page_stories(input.front_page_limit)
        digest = await build_tech_digest(stories, input.max_stories, today)
        audio_b64 = await generate_podcast_audio(digest.podcast_script, input.voice_id)

        subject = f"HN Tech Digest - {today} ({len(digest.stories)} stories)"
        audio_filename = f"hn-tech-digest-{today}.mp3"
        body_markdown = (
            digest.digest_markdown
            + "\n\n---\nPodcast-style audio digest (MP3, 1-2 minutes) is attached to this email.\n"
        )

        sent: dict = {}
        if not input.dry_run:
            sent = await send_digest_email(
                input.recipient,
                subject,
                body_markdown,
                render_digest_html(digest),
                audio_b64,
                audio_filename,
            )

        return HnTechDigestResult(
            recipient=input.recipient,
            subject=subject,
            story_count=len(digest.stories),
            digest_markdown=digest.digest_markdown,
            podcast_script_words=len(digest.podcast_script.split()),
            audio_filename=None if input.dry_run else audio_filename,
            audio_bytes=None if input.dry_run else len(audio_b64) * 3 // 4,
            email_message_id=sent.get("id"),
            email_thread_id=sent.get("threadId"),
            dry_run=input.dry_run,
        )
